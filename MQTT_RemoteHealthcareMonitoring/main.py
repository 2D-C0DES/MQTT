"""
IoT Remote Medical Diagnosis System — Main Simulation
======================================================
Full end-to-end simulation matching the paper:

  "An IoT based remote medical diagnosis system using
   one time pad cipher over MQTT protocol"
  Scientific Reports (2025) 15:42117

Architecture (from paper):
  ESP32 IoT Publisher (Patient) 
    → OTP Encrypt 
    → MQTT Broker (EMQX/MQTTx) 
    → OTP Decrypt 
    → Subscriber (Medical Expert)
    → Clinical Response (OTP Encrypted)
    → Patient

Execution sequence (paper, section 3.3):
  1. Medical clients implanted with sensors (registration)
  2. Communication key generated by Online Wrapper Application
  3. Medical Service Providers launch and authenticate
  4. Client connected to Service Provider via MQTT Broker
  5. Request accepted/rejected based on load and authentication
  6. If accepted: communication using wrapper-issued key
  7. If rejected: forwarded to suitable subscriber by broker

Run: python3 main.py
"""

