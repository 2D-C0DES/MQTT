def section(title: str) -> str:
    """Local helper for colored section headers."""
    try:
        from colorama import Fore, Style
        return f"\n{Fore.YELLOW + Style.BRIGHT}▶ {title}{Style.RESET_ALL}\n" + "─"*60
    except:
        return f"\n▶ {title}\n" + "─"*60

try:
    from colorama import Fore, Style
except:
    class Fore:
        RED = GREEN = YELLOW = ""
    class Style:
        BRIGHT = RESET_ALL = ""

def color(text, c=""):
    try:
        from colorama import Style
        return c + text + Style.RESET_ALL
    except:
        return text


