# ─────────────────────────────────────────────
#  Phase 6: Patient Mobility
# ─────────────────────────────────────────────

def phase6_mobility(patients: dict, broker_a: MQTTBroker,
                    broker_b: MQTTBroker, dash: Dashboard) -> dict:
    dash._p(f"\n{'='*78}")
    dash._p("  PHASE 6 — Patient Mobility (Broker Handover)")
    dash._p(f"{'='*78}")
    dash._p("  Simulating patient moving from Ward 1 (Zone-A) to Ward 2 (Zone-B)...")
    dash._p("  Paper: 'broker-broker communication to exchange configuration and")
    dash._p("          authentication information of a mobile node'")

    # Publish from Zone-A
    patient = list(patients.values())[0]
    pre = patient.publish_health_data(
        "health/status",
        f"Pre-handover: {patient.sensor.format_health_status()}",
        qos=QoSLevel.AT_LEAST_ONCE
    )
    dash._p(f"\n  Pre-handover publish: ✓ (Wire size: {pre['mqtt_result'].get('wire_size_bytes','?')} bytes)")

    # Handover
    time.sleep(0.1)
    result = patient.handover_to(broker_b)
    dash.print_handover(result)

    # Publish from Zone-B (new broker)
    post = patient.publish_health_data(
        "health/status",
        f"Post-handover: {patient.sensor.format_health_status()}",
        qos=QoSLevel.AT_LEAST_ONCE
    )
    dash._p(f"  Post-handover publish: ✓ on {broker_b.broker_id}")
    dash._p(f"  Continuous monitoring maintained: ✓ (Paper guarantee)")

    return {"pre_handover": pre, "handover": result, "post_handover": post}


