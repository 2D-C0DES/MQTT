# ─────────────────────────────────────────────
#  Phase 3: MQTT Communication
# ─────────────────────────────────────────────

def phase3_mqtt_communication(patients: dict, doctors: dict,
                               broker: MQTTBroker, dash: Dashboard) -> dict:
    dash._p(f"\n{'='*78}")
    dash._p("  PHASE 3 — MQTT Publish-Subscribe Communication")
    dash._p(f"{'='*78}")

    # Broker config
    dash.print_broker_config(broker.get_broker_summary())
    dash.print_acl_table()

    # Publish health data from each patient
    all_pub_results = []
    dash._p("\n  Publishing encrypted sensor data from patients...")
    
    for pid, patient in patients.items():
        results = patient.publish_sensor_data(qos=QoSLevel.AT_LEAST_ONCE)
        all_pub_results.extend(results)
        dash._p(f"  Patient {pid}: {len(results)} topics published")

    time.sleep(0.3)   # Allow callbacks to fire

    # Show publish results table (first 8)
    dash.print_publish_results(all_pub_results[:8])

    # Collect decrypted messages from doctors
    time.sleep(0.2)
    all_dec = []
    for did, doctor in doctors.items():
        msgs = doctor.received_messages
        all_dec.extend(msgs[:3])   # Show top 3 per doctor

    if all_dec:
        dash.print_decryption_results(all_dec[:8])

    # Doctor responses
    dash._p("\n  Doctor responses sent:")
    for did, doctor in doctors.items():
        for r in doctor.responses_sent[:2]:
            dash._p(f"  {did} ({doctor.specialization}) → "
                   f"Patient {r['patient_id']}: '{r['response_text'][:50]}'")

    return {
        "published": len(all_pub_results),
        "decrypted": len(all_dec),
        "broker": broker.get_broker_summary()
    }


