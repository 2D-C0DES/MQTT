def phase1_registration(patients: dict, doctors: dict, dash: Dashboard) -> dict:
    dash._p(f"\n{'='*78}")
    dash._p("  PHASE 1 — Registration & Connection (Paper Execution Steps 1-4)")
    dash._p(f"{'='*78}")

    results = {"patients": {}, "doctors": {}}

    # Step 1-2: Register patients
    for pid, patient in patients.items():
        reg_result = patient.register_and_connect()
        status = "✓ CONNECTED" if patient.connected else "✗ FAILED"
        dash._p(f"  Patient {pid}: {status} | Role: Patient | Broker: {patient.broker.broker_id}")
        results["patients"][pid] = reg_result

    # Step 3-4: Register and connect doctors
    for did, doctor in doctors.items():
        reg_result = doctor.register_and_connect()
        sub_result = doctor.subscribe_topics()
        status = "✓ CONNECTED" if doctor.connected else "✗ FAILED"
        dash._p(f"  Doctor  {did}: {status} | Role: {doctor.specialization}")
        results["doctors"][did] = {**reg_result, "subscriptions": sub_result}

    return results


