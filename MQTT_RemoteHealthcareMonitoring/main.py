def setup_system():
    """
    Initialise all system components:
      - MQTT Brokers (Zone-A and Zone-B for mobility demo)
      - Online Wrapper Application
      - Patient publishers (Medical Clients)
      - Doctor subscribers (Medical Practitioners)
      - Practitioner queue manager
    """
    # Dual-broker setup (patient mobility demo)
    broker_a = MQTTBroker("broker-zone-a.emqx.io", location="Zone-A (Ward 1)")
    broker_b = MQTTBroker("broker-zone-b.emqx.io", location="Zone-B (Ward 2)")

    # Online Wrapper Application
    wrapper = OnlineWrapperApp()

    # Patient registry (publisher ↔ subscriber key exchange)
    patient_registry: dict = {}

    # ── Patients (Publishers) ─────────────────────────────
    patients_config = [
        {"id": "MC1",  "name": "Medical Client 1"},
        {"id": "MC2",  "name": "Medical Client 2"},
        {"id": "MC3",  "name": "Medical Client 3"},
        {"id": "MC4",  "name": "Medical Client 4"},
        {"id": "MC5",  "name": "Medical Client 5"},
    ]

    patients = {}
    for cfg in patients_config:
        p = PatientPublisher(
            patient_id=cfg["id"],
            broker=broker_a,
            wrapper=wrapper,
            keys_dir=KEYS_DIR
        )
        patients[cfg["id"]] = p
        patient_registry[cfg["id"]] = p

    # ── Doctors (Subscribers) ────────────────────────────
    doctors_config = [
        {"id": "MP1", "specialization": "General Physician"},
        {"id": "MP2", "specialization": "Cardiologist"},
        {"id": "MP3", "specialization": "Psychologist"},
        {"id": "MP4", "specialization": "Pharmacologist"},
    ]

    doctors = {}
    for cfg in doctors_config:
        d = DoctorSubscriber(
            doctor_id=cfg["id"],
            specialization=cfg["specialization"],
            broker=broker_a,
            wrapper=wrapper,
            patient_publisher_registry=patient_registry,
            keys_dir=KEYS_DIR
        )
        doctors[cfg["id"]] = d

    # ── Practitioner Queue ────────────────────────────────
    pq = PractitionerQueueManager()
    for cfg in doctors_config:
        pq.register_practitioner(cfg["id"], cfg["specialization"])

    # Allocate patients to practitioners (Table 2)
    for pid in ["MC1", "MC4"]:
        pq.allocate(pid, "General Physician")
    for pid in ["MC2", "MC5"]:
        pq.allocate(pid, "Cardiologist")
    for pid in ["MC3"]:
        pq.allocate(pid, "Psychologist")

    return broker_a, broker_b, wrapper, patients, doctors, pq, patient_registry


